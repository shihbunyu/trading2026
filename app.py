import pandas as pd
import streamlit as st
import plotly.graph_objects as go

from trading import (
    analyze_results,
    calculate_moving_averages,
    get_stock_data,
    identify_golden_cross,
    implement_strategy,
)


st.set_page_config(
    page_title="Trading Strategy Dashboard",
    page_icon="📈",
    layout="wide",
)


@st.cache_data
def load_strategy_data():
    data = get_stock_data("MSFT")
    data = calculate_moving_averages(data)
    data = identify_golden_cross(data)
    positions = implement_strategy(data)
    summary = analyze_results(positions)
    return data, positions, summary


data, positions, summary = load_strategy_data()

st.title("MSFT Golden Cross Trading Dashboard")

price_tab, stats_tab, detail_tab = st.tabs([
    "Price Chart",
    "Trade Statistics",
    "Detailed Trades",
])

with price_tab:
    st.subheader("Price history and moving averages")

    if data.empty:
        st.warning("No price data available.")
    else:
        chart_df = data.reset_index().copy()
        chart_df.columns = [col if col != "index" else "Date" for col in chart_df.columns]
        if "Date" not in chart_df.columns:
            chart_df = chart_df.rename(columns={chart_df.columns[0]: "Date"})
        chart_df["Date"] = pd.to_datetime(chart_df["Date"])

        fig = go.Figure()
        fig.add_trace(
            go.Scatter(
                x=chart_df["Date"],
                y=chart_df["Close"],
                mode="lines",
                name="Stock Price",
                line={"color": "#1f77b4", "width": 2},
            )
        )
        fig.add_trace(
            go.Scatter(
                x=chart_df["Date"],
                y=chart_df["MA50"],
                mode="lines",
                name="Short-term MA (50)",
                line={"color": "#ff7f0e", "width": 2},
            )
        )
        fig.add_trace(
            go.Scatter(
                x=chart_df["Date"],
                y=chart_df["MA200"],
                mode="lines",
                name="Long-term MA (200)",
                line={"color": "#2ca02c", "width": 2, "dash": "dash"},
            )
        )

        if not positions.empty:
            buy_df = positions[["BuyDate", "BuyPrice"]].rename(columns={"BuyDate": "Date", "BuyPrice": "Price"})
            sell_df = positions[["SellDate", "SellPrice"]].rename(columns={"SellDate": "Date", "SellPrice": "Price"})

            fig.add_trace(
                go.Scatter(
                    x=pd.to_datetime(buy_df["Date"]),
                    y=buy_df["Price"],
                    mode="markers",
                    marker={"symbol": "circle", "size": 10, "color": "green", "line": {"width": 1, "color": "black"}},
                    name="Buy Signal",
                )
            )
            fig.add_trace(
                go.Scatter(
                    x=pd.to_datetime(sell_df["Date"]),
                    y=sell_df["Price"],
                    mode="markers",
                    marker={"symbol": "circle", "size": 10, "color": "red", "line": {"width": 1, "color": "black"}},
                    name="Sell Signal",
                )
            )

        fig.update_layout(
            title="MSFT Price with Moving Averages and Trade Signals",
            xaxis_title="Date",
            yaxis_title="Price",
            template="plotly_white",
            legend={"orientation": "h", "yanchor": "bottom", "y": 1.02, "xanchor": "left", "x": 0},
            hovermode="x unified",
            height=700,
        )
        st.plotly_chart(fig, use_container_width=True)

with stats_tab:
    st.subheader("Overall trade statistics")

    if positions.empty:
        st.info("No completed trades were generated by the strategy for the selected period.")
    else:
        col1, col2, col3, col4 = st.columns(4)
        col1.metric("Total Trades", summary["Total Trades"])
        col2.metric("Winning Trades", summary["Winning Trades"])
        col3.metric("Losing Trades", summary["Losing Trades"])
        col4.metric("Win Rate", f"{summary['Win Rate %']:.2f}%")

        col5, col6, col7, col8 = st.columns(4)
        col5.metric("Average Profit", f"{summary['Average Profit %']:.2f}%")
        col6.metric("Average Win", f"{summary['Average Win %']:.2f}%")
        col7.metric("Average Loss", f"{summary['Average Loss %']:.2f}%")
        col8.metric("Avg Holding Days", f"{summary['Average Holding Days']:.1f}")

        st.markdown("### Summary breakdown")
        stats_df = pd.DataFrame(
            [
                ["Target Reached", summary["Target Reached"]],
                ["Max Holding Period", summary["Max Holding Period"]],
            ],
            columns=["Exit Type", "Count"],
        )
        st.dataframe(stats_df, use_container_width=True, hide_index=True)

with detail_tab:
    st.subheader("Detailed trade records")

    if positions.empty:
        st.info("No trade details to show.")
    else:
        table_df = positions.copy()
        table_df["BuyDate"] = pd.to_datetime(table_df["BuyDate"]).dt.strftime("%Y-%m-%d")
        table_df["SellDate"] = pd.to_datetime(table_df["SellDate"]).dt.strftime("%Y-%m-%d")
        table_df["BuyPrice"] = table_df["BuyPrice"].round(2)
        table_df["SellPrice"] = table_df["SellPrice"].round(2)
        table_df["ProfitPct"] = table_df["ProfitPct"].round(2)
        table_df = table_df[
            [
                "BuyDate",
                "BuyPrice",
                "SellDate",
                "SellPrice",
                "HoldingDays",
                "ProfitPct",
                "SellReason",
            ]
        ]
        st.dataframe(table_df, use_container_width=True)
